# GoalWall

GoalWall is an Android goal-based lock-screen wallpaper app.

## Source

The initial Android Kotlin source project is provided in `GoalWall-Android-Source.zip`. Extract it and open the project folder in Android Studio.

## Current scope
- Create goals and mark them complete
- Track per-goal and overall streaks
- Six wallpaper visual styles: Calendar Heatmap, Streak Rings, Streak Chain, Growing Tree, Constellation, and Mountain Progress
- Apply generated wallpaper to the Android lock screen

## Build status
This is a starter source project and has not yet been build-tested. Review and build it in Android Studio before use.